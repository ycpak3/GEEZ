const counts = [0, 0, 0];
globalThis.GEEZ_QUESTIONS = bank.map((line, i) => {
  const [clue, category, difficulty, question, raw, decoys, explain] = line.split("|");
  const level = Number(difficulty);
  const appearanceIndex = counts[level]++;
  const art = level * 3 + (appearanceIndex % 3);
  const answers = raw.split(",").map((a) => a.trim()).filter(Boolean);
  const choices = decoys ? decoys.split(",") : [];
  // 문항 순번으로 정답 위치를 정해 다시 열어도 보기 순서가 같다.
  if (choices.length) {
    const answerIndex = (i + Math.floor(i / 3) + 1) % 4;
    choices.splice(answerIndex, 0, answers[0]);
  }
  return {
    id: "g" + (i + 1),
    name: clue,
    art,
    tags: ["일반상식", category],
    question,
    choices,
    answers,
    explain,
    seconds: level === 2 ? 60 : 0,
    created: 0,
  };
});
